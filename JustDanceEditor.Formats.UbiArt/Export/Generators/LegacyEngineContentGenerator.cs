        WriteString(writer, mapName);
        WriteBigEndian32(writer, (uint)EngineVersion);
        WriteBigEndian32(writer, package.Metadata.OriginalJDVersion);

        // RelatedAlbums
        writer.Write([0x00, 0x00, 0x00, 0x00]);

