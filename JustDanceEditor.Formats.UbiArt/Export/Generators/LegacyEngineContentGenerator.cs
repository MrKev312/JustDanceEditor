        writer.Write(new byte[16]);
        writer.Write([0xFF, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]);

        // Texture type logic
        // Modern: textureName.EndsWith("_map_bkg") ? 0x01 : 0x06
