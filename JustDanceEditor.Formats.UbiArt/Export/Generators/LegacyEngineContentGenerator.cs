        using MemoryStream ms = new();
        using BinaryWriter writer = new(ms);

        // Header
        writer.Write([
            0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x15, 0xA5, 0x1B, 0x85, 0x7B, 0xCE, 0x00, 0x00, 0x00, 0x6C,
